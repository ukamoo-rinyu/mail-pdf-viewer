"""test_document_mode.py用の、しおり付き一般資料PDF(ダミー内容)を生成する。

個人情報を含む実際のメールPDFはリポジトリに含めないため、
資料モードのテストに必要な最小限のサンプルをこのスクリプトで都度生成する。
"""
import fitz

doc = fitz.open()
texts = [
    "第1章 はじめに\nこれは第1章の本文です。テスト用のダミーテキストです。",
    "1.1 背景\n背景に関する説明文です。予算やスケジュールについて記載します。",
    "1.2 目的\n目的に関する説明文です。キーワード:電気工事 見積書",
    "第2章 詳細設計\n詳細設計の概要です。",
    "2.1 構造\n構造に関する説明。キーワード:配管 図面",
    "付録A 見積書\n見積書のダミー内容です。金額:12345円",
]
for t in texts:
    page = doc.new_page(width=595, height=842)
    page.insert_text((72, 72), t, fontsize=11)

toc = [
    [1, "第1章 はじめに", 1],
    [2, "1.1 背景", 2],
    [2, "1.2 目的", 3],
    [1, "第2章 詳細設計", 4],
    [2, "2.1 構造", 5],
    [1, "付録A 見積書", 6],
]
doc.set_toc(toc)

out = "../一般資料サンプル.pdf"
doc.save(out)
doc.close()
print("saved", out)
